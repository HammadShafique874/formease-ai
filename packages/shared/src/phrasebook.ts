// Deterministic curated phrasebook — NOT AI.
// Every entry is hand-written in English, Simple English and Roman Urdu.
// Unknown fields get a generic fallback that re-uses the original label and
// says so; nothing here is ever presented as an AI explanation.
import type { Language } from "./types.js";

export interface PhrasebookEntry {
  key: string;
  /** Lower-case substrings that match a field label. First match wins. */
  match: string[];
  explanations: Record<Language, string>;
  requiredInformation: string[];
  possibleDocuments: string[];
  commonMistakes: string[];
  exampleAnswer?: string;
}

function e(
  key: string,
  match: string[],
  en: string,
  simple: string,
  roman: string,
  requiredInformation: string[],
  possibleDocuments: string[],
  commonMistakes: string[],
  exampleAnswer?: string,
): PhrasebookEntry {
  return {
    key,
    match,
    explanations: { en, "simple-en": simple, "roman-ur": roman },
    requiredInformation,
    possibleDocuments,
    commonMistakes,
    exampleAnswer,
  };
}

