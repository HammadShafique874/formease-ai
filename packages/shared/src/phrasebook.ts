const NORMALISE = (s: string): string => s.toLowerCase().replace(/[^a-z0-9 ]+/g, " ").replace(/\s+/g, " ").trim();

export function lookupPhrasebook(label: string): PhrasebookEntry | null {
  const norm = NORMALISE(label);
  if (!norm) return null;
  for (const entry of PHRASEBOOK) {
    if (entry.match.some((m) => norm.includes(NORMALISE(m)))) return entry;
  }
  return null;
}

/** Generic fallback — never invents a translation. It re-uses the original label. */
export function genericFallbackExplanation(label: string, language: Language): string {
  const clean = label.replace(/[?*:]+$/g, "").trim();
  if (language === "roman-ur") return `Yahan "${clean}" ke baare mein woh maloomat likhein jo form maang raha hai. (Is field ke liye phrasebook mein abhi koi entry nahi hai.)`;
  if (language === "simple-en") return `Write here the information this form asks for in "${clean}". (No phrasebook entry for this field yet.)`;
  return `Enter the information this form asks for in "${clean}". (No phrasebook entry for this field yet.)`;
}
