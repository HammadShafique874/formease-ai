// localStorage persistence — versioned keys, try/catch everywhere, validated on load.
import type { DocumentItem, FormGuide, SavedGuide } from "@formease/shared";
import { newId, validateFormGuide } from "@formease/shared";

const GUIDES_KEY = "formease:v1:guides";
const CHECKLIST_KEY = "formease:v1:checklist";
const CHECKLIST_ITEMS_KEY = "formease:v1:checklist-items";
const ACTIVITY_KEY = "formease:v1:activity";
const DEMO_KEY = "formease:v1:demo";

export interface StorageError {
  message: string;
}

function isQuotaError(err: unknown): boolean {
  return err instanceof DOMException && (err.name === "QuotaExceededError" || err.name === "NS_ERROR_DOM_QUOTA_REACHED");
}

export function saveGuides(guides: SavedGuide[]): string | null {
  try {
    window.localStorage.setItem(GUIDES_KEY, JSON.stringify(guides));
    return null;
  } catch (err) {
    return isQuotaError(err)
      ? "Browser storage is full — delete an old guide and try again."
      : "Could not save to browser storage (it may be unavailable in private mode).";
  }
}

export function loadGuides(): SavedGuide[] {
  try {
    const raw = window.localStorage.getItem(GUIDES_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((g): g is SavedGuide => {
      if (typeof g !== "object" || g === null) return false;
      const rec = g as Record<string, unknown>;
      return typeof rec.id === "string" && validateFormGuide(rec.guide).ok;
    });
  } catch {
    return [];
  }
}

export function upsertGuide(guide: FormGuide): { guides: SavedGuide[]; error: string | null } {
  const guides = loadGuides();
  const saved: SavedGuide = { id: guide.id, title: guide.title, guide, savedAt: new Date().toISOString() };
  const idx = guides.findIndex((g) => g.id === guide.id);
  if (idx >= 0) guides[idx] = saved; else guides.unshift(saved);
  const error = saveGuides(guides);
  if (!error) logActivity(`Saved guide "${guide.title}"`);
  return { guides, error };
}

export function deleteGuide(id: string): SavedGuide[] {
  const guides = loadGuides().filter((g) => g.id !== id);
  saveGuides(guides);
  return guides;
}

export function renameGuide(id: string, title: string): SavedGuide[] {
  const guides = loadGuides().map((g) => (g.id === id ? { ...g, title, guide: { ...g.guide, title } } : g));
  saveGuides(guides);
  return guides;
}

export function duplicateGuide(id: string): SavedGuide[] {
  const guides = loadGuides();
  const found = guides.find((g) => g.id === id);
  if (!found) return guides;
  const copy: SavedGuide = {
    id: newId("guide"),
    title: `${found.title} (copy)`,
    guide: { ...found.guide, id: newId("guide"), title: `${found.title} (copy)`, updatedAt: new Date().toISOString() },
    savedAt: new Date().toISOString(),
  };
  guides.unshift(copy);
  saveGuides(guides);
  return guides;
}

export function exportGuideMarkdown(guide: FormGuide): string {
  const lines: string[] = [`# ${guide.title}`, ``, `Source: ${guide.sourceLabel} · Language: ${guide.language}`, ``];
  for (const f of guide.fields) {
    lines.push(`## ${f.fieldLabel}`, ``, `${f.simpleExplanation}`, ``);
    if (f.exampleAnswer) lines.push(`Example: ${f.exampleAnswer}`, ``);
    if (f.requiredInformation.length > 0) lines.push(`Required information:`, ...f.requiredInformation.map((r) => `- ${r}`), ``);
    if (f.possibleDocuments.length > 0) lines.push(`Possible documents:`, ...f.possibleDocuments.map((r) => `- ${r}`), ``);
  }
  if (guide.fields.length === 0) {
    lines.push(`Detected fields:`, ...guide.detectedLabels.map((l) => `- ${l}`), ``);
  }
  const aiCount = guide.fields.filter((f) => f.source === "ai").length;
  lines.push(aiCount > 0
    ? `_Generated by FormEase AI. ${String(aiCount)} field(s) explained by Firebase AI Logic Hybrid Inference (route: ${guide.inferenceRoute}); the rest are from the local phrasebook/parser._`
    : `_Generated locally by FormEase AI. Explanations are from the local phrasebook/parser — AI unavailable (Firebase not configured)._`);
  return lines.join("\n");
}

export function downloadText(filename: string, text: string, mime: string): void {
  const blob = new Blob([text], { type: mime });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  a.click();
  URL.revokeObjectURL(a.href);
}

/* ---- Checklist (per-guide + global items) ---- */
export interface ChecklistState { [guideId: string]: { [docId: string]: boolean } }
export function loadChecklist(): ChecklistState {
  try {
    const raw = window.localStorage.getItem(CHECKLIST_KEY);
    return raw ? (JSON.parse(raw) as ChecklistState) : {};
  } catch { return {}; }
}
export function saveChecklist(state: ChecklistState): void {
  try { window.localStorage.setItem(CHECKLIST_KEY, JSON.stringify(state)); } catch { /* ignore */ }
}
export function loadChecklistItems(): DocumentItem[] {
  try {
    const raw = window.localStorage.getItem(CHECKLIST_ITEMS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    return Array.isArray(parsed) ? parsed.filter((i): i is DocumentItem => typeof i === "object" && i !== null && typeof (i as DocumentItem).name === "string") : [];
  } catch { return []; }
}
export function saveChecklistItems(items: DocumentItem[]): void {
  try { window.localStorage.setItem(CHECKLIST_ITEMS_KEY, JSON.stringify(items)); } catch { /* ignore */ }
}

/* ---- Activity log (drives real Dashboard stats) ---- */
export interface ActivityEntry { id: string; text: string; at: string }
export function loadActivity(): ActivityEntry[] {
  try {
    const raw = window.localStorage.getItem(ACTIVITY_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    return Array.isArray(parsed) ? (parsed as ActivityEntry[]).filter((a) => typeof a?.text === "string") : [];
  } catch { return []; }
}
export function logActivity(text: string): void {
  try {
    const entries = loadActivity();
    entries.unshift({ id: newId("act"), text, at: new Date().toISOString() });
    window.localStorage.setItem(ACTIVITY_KEY, JSON.stringify(entries.slice(0, 30)));
  } catch { /* ignore */ }
}

/* ---- Demo data ---- */
export function isDemoLoaded(): boolean {
  try { return window.localStorage.getItem(DEMO_KEY) === "1"; } catch { return false; }
}
export function setDemoLoaded(v: boolean): void {
  try { window.localStorage.setItem(DEMO_KEY, v ? "1" : "0"); } catch { /* ignore */ }
}

export function clearAllFormEaseData(): void {
  try {
    for (const key of Object.keys(window.localStorage)) {
      if (key.startsWith("formease:")) window.localStorage.removeItem(key);
    }
  } catch { /* ignore */ }
}
